export function calculateFinalScore(
  kelancaran: number,
  tajwid: number,
  makhraj: number,
  fashahah: number,
  adab: number
): number {
  const finalScore =
    kelancaran * 0.3 +
    tajwid * 0.25 +
    makhraj * 0.2 +
    fashahah * 0.15 +
    adab * 0.1;
  return Math.round(finalScore);
}
